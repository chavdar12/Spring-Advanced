package bg.softuni.docs;

import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.DecimalMin;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;

import java.math.BigDecimal;

@Schema(description = "A course students can enroll in")
public record CourseDTO(
        @Schema(description = "Generated by the server", accessMode = Schema.AccessMode.READ_ONLY) Long id,
        @Schema(example = "Spring Advanced") @NotBlank String name,
        @Schema(example = "120.00") @NotNull @DecimalMin("0") BigDecimal price) {

    static CourseDTO of(CourseEntity entity) {
        return new CourseDTO(entity.getId(), entity.getName(), entity.getPrice());
    }
}
